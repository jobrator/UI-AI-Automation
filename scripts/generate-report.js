#!/usr/bin/env node
/**
 * generate-report.js — Builds a consolidated HTML report from the Cucumber JSON outputs
 * produced by the chrome and firefox runs.
 *
 * Looks for:
 *   reports/cucumber-report.json
 *   reports/cucumber-report-chrome.json
 *   reports/cucumber-report-firefox.json
 *
 * Outputs:
 *   reports/html/index.html
 */

'use strict';

const path = require('path');
const fs = require('fs');
const report = require('multiple-cucumber-html-reporter');

const reportsDir = path.resolve('reports');
// The reporter globs every *.json in jsonDir, so it must be a directory holding
// ONLY this run's output — pointed at reports/ it also ingested kept snapshots
// and unrelated files like retest-sprint58.json.
const jsonDir = path.join(reportsDir, 'json-current');
const htmlDir = path.join(reportsDir, 'html');

// Only this run's JSON files. A prefix glob would also sweep up kept snapshots
// (cucumber-report-fullrun.json, cucumber-report-prev-*.json) and silently
// double-count old scenarios into the report.
const CURRENT_RUN_JSON = [
  'cucumber-report.json',
  'cucumber-report-chrome.json',
  'cucumber-report-firefox.json'
];

const jsonFiles = CURRENT_RUN_JSON.filter((f) => {
  const full = path.join(reportsDir, f);
  return fs.existsSync(full) && fs.statSync(full).size > 0;
});

// Stage this run's JSON into the clean directory the reporter reads.
fs.rmSync(jsonDir, { recursive: true, force: true });
fs.mkdirSync(jsonDir, { recursive: true });
for (const f of jsonFiles) {
  fs.copyFileSync(path.join(reportsDir, f), path.join(jsonDir, f));
}

if (jsonFiles.length === 0) {
  console.warn('[report] No cucumber JSON files found — skipping HTML report.');
  process.exit(0);
}

console.log(`[report] Building HTML report from ${jsonFiles.length} JSON file(s)...`);

report.generate({
  jsonDir,
  reportPath: htmlDir,
  pageTitle: 'Jobrator E2E Report',
  reportName: 'Jobrator BDD Automation Results',
  displayDuration: true,
  durationInMS: false,
  pageFooter: '<div style="text-align:center"><p>Jobrator E2E — generated by multiple-cucumber-html-reporter</p></div>',
  metadata: {
    browser: { name: 'multi', version: 'chromium + firefox' },
    device: 'CI / Local',
    platform: { name: process.platform, version: process.version }
  },
  customData: {
    title: 'Run Info',
    data: [
      { label: 'Project', value: 'Jobrator BDD E2E' },
      { label: 'Site', value: process.env.JOBRATOR_SITE || 'https://jobrator.com/' },
      { label: 'Date', value: new Date().toISOString() },
      { label: 'Standards', value: 'ISTQB + OWASP' }
    ]
  }
});

console.log(`[report] ✅ HTML report → ${path.join(htmlDir, 'index.html')}`);
